#!/usr/bin/env bash
# AES — Structural outline for the design note (standard/10 §5).
#
# Lists the versioned files and their public signatures (types, exported functions), without the
# implementations' code. It is a tool-generated fact: the orchestrator decides the
# design with this, not with another agent's description of the code.
#
# Usage: aes-outline.sh [<ref>] [<path>...]      e.g.  aes-outline.sh origin/dev src web/src
#   <ref>   commit or branch to outline (HEAD by default)
#   <path>  directories to include (by default, everything versioned except tests/acceptance and docs)
# Variables: AES_OUTLINE_MAX (maximum output lines, 600 by default).
#
# Languages: C#, TypeScript/JavaScript, Python, bash. For others, the file appears without signatures.
set -euo pipefail

ref="HEAD"
if [[ $# -gt 0 ]] && git rev-parse --verify --quiet "$1^{commit}" >/dev/null; then ref="$1"; shift; fi
max="${AES_OUTLINE_MAX:-600}"

if [[ $# -gt 0 ]]; then
  files=$(git ls-tree -r --name-only "$ref" -- "$@")
else
  files=$(git ls-tree -r --name-only "$ref" | grep -Ev '^(tests/acceptance/|docs/|specs/|\.github/|\.claude/)' || true)
fi
files=$(grep -Ev '(^|/)(node_modules|bin|obj|dist|build|Migrations)/|\.(lock|json|md|svg|png|jpg|ico|css)$|package-lock\.json$' <<< "$files" || true)

signatures() {  # signatures <path> : prints the file's public signatures at <ref>
  local path="$1" re
  case "$path" in
    *.cs)  re='^[[:space:]]*(public|internal|protected)[[:space:]].*(class|interface|record|struct|enum|delegate)[[:space:]]+[A-Za-z_]|^[[:space:]]*public[[:space:]][^=;]*\(' ;;
    *.ts|*.tsx|*.js|*.jsx|*.mjs) re='^export[[:space:]]+(default[[:space:]]+)?(async[[:space:]]+)?(function|class|const|let|interface|type|enum)[[:space:]]' ;;
    *.py)  re='^(async[[:space:]]+)?(def|class)[[:space:]]+[A-Za-z_]' ;;
    *.sh|*.bash) re='^[[:space:]]*(function[[:space:]]+)?[A-Za-z_][A-Za-z0-9_]*[[:space:]]*\(\)[[:space:]]*\{' ;;
    *) return 0 ;;
  esac
  git show "$ref:$path" 2>/dev/null \
    | grep -nE "$re" \
    | sed -E 's/[[:space:]]*(\{|=>).*$//; s/[[:space:]]+/ /g; s/^([0-9]+): ?(.*)$/    \2  (l.\1)/'
}

{
  echo "# Structural outline ($ref, $(git rev-parse --short "$ref"))"
  echo
  echo "Versioned files and public signatures, without implementations. Generated by aes-outline.sh."
  echo
  current_dir=""
  while IFS= read -r f; do
    [[ -z "$f" ]] && continue
    dir=$(dirname "$f")
    if [[ "$dir" != "$current_dir" ]]; then echo; echo "## $dir/"; current_dir="$dir"; fi
    echo "- $(basename "$f")"
    signatures "$f"
  done <<< "$files"
} | head -n "$max"
